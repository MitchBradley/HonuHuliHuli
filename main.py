# HonuHuliHuli - pushbutton turntable indexer for MicroPython on ESP32.
#
# A 200 step/rev stepper drives the turntable directly through a STEP/DIR
# driver.  Only STEP is driven by this code; DIR and ENABLE are hardwired.
#
#   Short press        index 1/8 turn.  Presses accumulate, so three quick
#                      presses (even while moving) index 3/8 turn.
#   Hold > 1 second    start continuous rotation (as soon as 1 s is reached).
#   Any press while    decelerate and stop exactly on the next 1/8 position
#   rotating           that can be reached at the configured acceleration.
#
# Step pulses are generated by the RMT peripheral from precomputed chunks
# of pulse timings, so the timing is jitter-free and Python stays free to
# watch the button and compute the next chunk while the current one plays.

from machine import Pin
from micropython import const
from time import ticks_ms, ticks_diff, sleep_ms
from math import sqrt
import esp32

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

STEP_PIN = const(4)          # GPIO to the driver's STEP input
BUTTON_PIN = const(5)        # GPIO to the pushbutton
BUTTON_ACTIVE_LOW = True     # True: button to GND, internal pull-up enabled

FULL_STEPS_PER_REV = const(200)
MICROSTEPS = const(16)       # Must match the driver's microstep setting

ACCELERATION = 0.5           # rev/s^2, used for all speed changes
CONTINUOUS_RPM = 10.0        # Speed for continuous rotation
INDEX_RPM = 30.0             # Top speed for 1/8 index moves (short moves
                             # may never reach it before decelerating)

DIVISIONS = const(8)         # Index increment is 1/DIVISIONS of a turn
LONG_PRESS_MS = const(1000)  # Hold this long to start continuous rotation
DEBOUNCE_MS = const(30)

STEP_PULSE_US = const(5)     # STEP high time; check the driver's minimum
RMT_CHANNEL = const(0)
CHUNK_MS = const(40)         # Approx. duration of each queued pulse chunk
MAX_CHUNK_STEPS = const(1000)  # Caps chunk memory at very high step rates

# ---------------------------------------------------------------------------

STEPS_PER_REV = FULL_STEPS_PER_REV * MICROSTEPS
STEPS_PER_INDEX = STEPS_PER_REV // DIVISIONS

TICKS_PER_SEC = 1_000_000    # RMT tick is 1 us
MAX_TICKS = 32767            # RMT 15-bit duration field

ACCEL_STEPS = ACCELERATION * STEPS_PER_REV       # steps/s^2
TWO_A = 2.0 * ACCEL_STEPS                         # v^2 change per step
CONT_V2 = (CONTINUOUS_RPM / 60.0 * STEPS_PER_REV) ** 2
INDEX_V2 = (INDEX_RPM / 60.0 * STEPS_PER_REV) ** 2

# Starting/stopping speed: the speed reached after one step from rest, but
# never slower than the longest interval the RMT can express in one item.
_min_v = TICKS_PER_SEC / (MAX_TICKS + STEP_PULSE_US - 1)
START_V2 = max(TWO_A, _min_v * _min_v)

CHUNK_TICKS = CHUNK_MS * (TICKS_PER_SEC // 1000)


def make_rmt():
    pin = Pin(STEP_PIN, Pin.OUT, value=0)
    # The esp32.RMT constructor changed when MicroPython moved to the
    # ESP-IDF 5 RMT driver; try the newer form first, then the older one.
    try:
        return esp32.RMT(RMT_CHANNEL, pin=pin, resolution_hz=TICKS_PER_SEC,
                         idle_level=False)
    except (TypeError, ValueError):
        pass
    # Older API: ticks are source_freq / clock_div (source is 80 MHz).
    return esp32.RMT(RMT_CHANNEL, pin=pin, clock_div=80, idle_level=False)


class Motion:
    """Generates step timing for a trapezoidal velocity profile.

    pos and target are absolute microstep counts from power-up, which is
    treated as index position 0.  target is None during continuous rotation.
    v2 is the square of the speed (steps/s) for the next step, so each step
    changes it by exactly 2*a, which keeps the acceleration exact.
    """

    def __init__(self):
        self.pos = 0
        self.target = 0
        self.vmax2 = INDEX_V2
        self.v2 = START_V2
        self.frac = 0.0
        self._cache_v2 = -1.0
        self._cache_ticks = 0.0

    def active(self):
        return self.target is None or self.pos < self.target

    def continuous(self):
        return self.target is None

    def add_index(self):
        if self.target is None:
            return
        self.target += STEPS_PER_INDEX

    def start_continuous(self):
        self.target = None
        self.vmax2 = CONT_V2

    def stop_continuous(self):
        if self.target is not None:
            return
        # Steps needed to decelerate from the current speed, rounded up to
        # the next index boundary.  vmax stays at the continuous speed so a
        # long coast to the boundary does not speed up to INDEX_RPM.
        stop_steps = int((self.v2 - START_V2) / TWO_A) + 1
        p = self.pos + stop_steps
        self.target = -(-p // STEPS_PER_INDEX) * STEPS_PER_INDEX

    def build_chunk(self):
        """Return a list of RMT durations [high, low, high, low, ...] for
        roughly CHUNK_MS of motion, or None if the move is complete."""
        out = []
        t = 0
        n = 0
        while t < CHUNK_TICKS and n < MAX_CHUNK_STEPS:
            target = self.target
            if target is not None and self.pos >= target:
                break
            v2 = self.v2
            if v2 != self._cache_v2:
                self._cache_v2 = v2
                self._cache_ticks = TICKS_PER_SEC / sqrt(v2)
            # Carry the fractional tick so the average rate is exact
            self.frac += self._cache_ticks
            ticks = int(self.frac)
            self.frac -= ticks
            if ticks > MAX_TICKS + STEP_PULSE_US - 1:
                ticks = MAX_TICKS + STEP_PULSE_US - 1
            out.append(STEP_PULSE_US)
            out.append(ticks - STEP_PULSE_US)
            t += ticks
            n += 1
            self.pos += 1

            # Speed for the following step
            if target is not None and target - self.pos <= (v2 - START_V2) / TWO_A:
                v2 -= TWO_A
                if v2 < START_V2:
                    v2 = START_V2
            elif v2 < self.vmax2:
                v2 += TWO_A
                if v2 > self.vmax2:
                    v2 = self.vmax2
            elif v2 > self.vmax2:
                v2 -= TWO_A
                if v2 < self.vmax2:
                    v2 = self.vmax2
            self.v2 = v2

        if not self.active():
            # Move complete: next move starts from rest at index speed
            self.v2 = START_V2
            self.vmax2 = INDEX_V2
            self.frac = 0.0
        return out if out else None


PRESS = const(1)
RELEASE = const(2)
LONG = const(3)


class Button:
    def __init__(self, gpio):
        pull = Pin.PULL_UP if BUTTON_ACTIVE_LOW else Pin.PULL_DOWN
        self.pin = Pin(gpio, Pin.IN, pull)
        self.raw = self.read()
        self.stable = self.raw
        self.changed_t = ticks_ms()
        self.press_t = 0
        self.long_sent = False

    def read(self):
        return self.pin.value() == (0 if BUTTON_ACTIVE_LOW else 1)

    def poll(self):
        """Return PRESS, RELEASE, LONG, or None."""
        now = ticks_ms()
        raw = self.read()
        if raw != self.raw:
            self.raw = raw
            self.changed_t = now
            return None
        if raw != self.stable and ticks_diff(now, self.changed_t) >= DEBOUNCE_MS:
            self.stable = raw
            if raw:
                self.press_t = now
                self.long_sent = False
                return PRESS
            return RELEASE
        if (self.stable and not self.long_sent
                and ticks_diff(now, self.press_t) >= LONG_PRESS_MS):
            self.long_sent = True
            return LONG
        return None


def check_config():
    if STEPS_PER_REV % DIVISIONS:
        raise ValueError("STEPS_PER_REV not divisible by DIVISIONS")
    min_interval = TICKS_PER_SEC / sqrt(max(CONT_V2, INDEX_V2))
    if min_interval < 2 * STEP_PULSE_US:
        raise ValueError("Speed too high for STEP_PULSE_US")


def main():
    check_config()
    rmt = make_rmt()
    button = Button(BUTTON_PIN)
    motion = Motion()
    pending = None
    # True when the current press has already been used (to stop continuous
    # rotation or to start it), so its release is not a short press.
    consumed = False

    print("HonuHuliHuli: %d steps/rev, %d steps per 1/%d turn"
          % (STEPS_PER_REV, STEPS_PER_INDEX, DIVISIONS))

    while True:
        ev = button.poll()
        if ev == PRESS:
            consumed = False
            if motion.continuous():
                motion.stop_continuous()
                consumed = True
        elif ev == LONG:
            if not consumed:
                motion.start_continuous()
                consumed = True
        elif ev == RELEASE:
            if not consumed:
                motion.add_index()

        # Keep one chunk computed ahead of the one the RMT is playing
        if pending is None and motion.active():
            pending = motion.build_chunk()
        if pending is not None:
            if rmt.wait_done():
                rmt.write_pulses(pending, True)
                pending = None
        else:
            sleep_ms(5)


if __name__ == "__main__":
    main()
