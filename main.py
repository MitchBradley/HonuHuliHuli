# HonuHuliHuli - pushbutton turntable indexer for MicroPython on ESP32.
#
# A 200 step/rev stepper drives the turntable directly through a STEP/DIR
# driver.  STEP and an active-high ENABLE are driven; DIR is hardwired.
#
#   Short press        index 1/8 turn.  Presses accumulate, so three quick
#                      presses (even while moving) index 3/8 turn.
#   Hold > 1 second    start continuous rotation (as soon as 1 s is reached).
#   Any press while    decelerate and stop exactly on the next 1/8 position
#   rotating           that can be reached at the configured acceleration.
#
# Step pulses are generated by the RMT peripheral from precomputed chunks
# of pulse timings, so the timing is jitter-free and Python stays free to
# watch the button and compute the next chunk while the current one plays.

from machine import Pin
from micropython import const
from time import ticks_ms, ticks_us, ticks_add, ticks_diff, sleep_ms
from math import sqrt, sin, cos
import esp32

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

STEP_PIN = const(16)          # GPIO to the driver's STEP input
BUTTON_PIN = const(18)        # GPIO to the pushbutton
ENABLE_PIN = const(33)       # GPIO to the driver's ENABLE input (active high)
ENABLE_AT_BOOT = True        # Energize the motor when the app starts
UV_PIN = const(35)           # GPIO to the UV light relay (active high); on
                             # from reaching continuous speed to stop press
BUTTON_ACTIVE_LOW = True     # True: button to GND, internal pull-up enabled

FULL_STEPS_PER_REV = const(200)
MICROSTEPS = const(8)       # Must match the driver's microstep setting

ACCELERATION = 0.5           # rev/s^2, used for all speed changes
CONTINUOUS_RPM = 10.0        # Speed for continuous rotation
INDEX_RPM = 30.0             # Top speed for 1/8 index moves (short moves


DIVISIONS = const(8)         # Index increment is 1/DIVISIONS of a turn
LONG_PRESS_MS = const(1000)  # Hold this long to start continuous rotation
DEBOUNCE_MS = const(30)

STEP_PULSE_US = const(5)     # STEP high time; check the driver's minimum
RMT_CHANNEL = const(0)
CHUNK_MS = const(40)         # Approx. duration of each queued pulse chunk
MAX_CHUNK_STEPS = const(1000)  # Caps chunk memory at very high step rates

# ---------------------------------------------------------------------------

STEPS_PER_REV = FULL_STEPS_PER_REV * MICROSTEPS
STEPS_PER_INDEX = STEPS_PER_REV // DIVISIONS

TICKS_PER_SEC = 1_000_000    # RMT tick is 1 us
MAX_TICKS = 32767            # RMT 15-bit duration field

ACCEL_STEPS = ACCELERATION * STEPS_PER_REV       # steps/s^2
TWO_A = 2.0 * ACCEL_STEPS                         # v^2 change per step
CONT_V2 = (CONTINUOUS_RPM / 60.0 * STEPS_PER_REV) ** 2
INDEX_V2 = (INDEX_RPM / 60.0 * STEPS_PER_REV) ** 2

# Starting/stopping speed: the speed reached after one step from rest, but
# never slower than the longest interval the RMT can express in one item.
_min_v = TICKS_PER_SEC / (MAX_TICKS + STEP_PULSE_US - 1)
START_V2 = max(TWO_A, _min_v * _min_v)

CHUNK_TICKS = CHUNK_MS * (TICKS_PER_SEC // 1000)


def make_rmt():
    pin = Pin(STEP_PIN, Pin.OUT, value=0)
    # The esp32.RMT constructor changed when MicroPython moved to the
    # ESP-IDF 5 RMT driver; try the newer form first, then the older one.
    try:
        return esp32.RMT(RMT_CHANNEL, pin=pin, resolution_hz=TICKS_PER_SEC,
                         idle_level=False)
    except (TypeError, ValueError):
        pass
    # Older API: ticks are source_freq / clock_div (source is 80 MHz).
    return esp32.RMT(RMT_CHANNEL, pin=pin, clock_div=80, idle_level=False)


class Motion:
    """Generates step timing for a trapezoidal velocity profile.

    pos and target are absolute microstep counts from power-up, which is
    treated as index position 0.  target is None during continuous rotation.
    v2 is the square of the speed (steps/s) for the next step, so each step
    changes it by exactly 2*a, which keeps the acceleration exact.
    """

    def __init__(self):
        self.pos = 0
        self.target = 0
        self.vmax2 = INDEX_V2
        self.v2 = START_V2
        self.frac = 0.0
        self._cache_v2 = -1.0
        self._cache_ticks = 0.0
        # UV light state as of the last generated step, and the
        # (tick offset, level) changes within the chunk being built.
        self.uv = False
        self.events = []

    def active(self):
        return self.target is None or self.pos < self.target

    def continuous(self):
        return self.target is None

    def add_index(self):
        if self.target is None:
            return
        self.target += STEPS_PER_INDEX

    def start_continuous(self):
        self.target = None
        self.vmax2 = CONT_V2

    def stop_continuous(self):
        if self.target is not None:
            return
        # Steps needed to decelerate from the current speed, rounded up to
        # the next index boundary.  vmax stays at the continuous speed so a
        # long coast to the boundary does not speed up to INDEX_RPM.
        stop_steps = int((self.v2 - START_V2) / TWO_A) + 1
        p = self.pos + stop_steps
        self.target = -(-p // STEPS_PER_INDEX) * STEPS_PER_INDEX

    def build_chunk(self):
        """Return a list of RMT durations [high, low, high, low, ...] for
        roughly CHUNK_MS of motion, or None if the move is complete."""
        out = []
        t = 0
        n = 0
        while t < CHUNK_TICKS and n < MAX_CHUNK_STEPS:
            target = self.target
            if target is not None and self.pos >= target:
                break
            v2 = self.v2
            if v2 != self._cache_v2:
                self._cache_v2 = v2
                self._cache_ticks = TICKS_PER_SEC / sqrt(v2)
            # Carry the fractional tick so the average rate is exact
            self.frac += self._cache_ticks
            ticks = int(self.frac)
            self.frac -= ticks
            if ticks > MAX_TICKS + STEP_PULSE_US - 1:
                ticks = MAX_TICKS + STEP_PULSE_US - 1
            out.append(STEP_PULSE_US)
            out.append(ticks - STEP_PULSE_US)
            t += ticks
            n += 1
            self.pos += 1

            # Speed for the following step
            if target is not None and target - self.pos <= (v2 - START_V2) / TWO_A:
                v2 -= TWO_A
                if v2 < START_V2:
                    v2 = START_V2
            elif v2 < self.vmax2:
                v2 += TWO_A
                if v2 > self.vmax2:
                    v2 = self.vmax2
            elif v2 > self.vmax2:
                v2 -= TWO_A
                if v2 < self.vmax2:
                    v2 = self.vmax2
            self.v2 = v2
            if target is None and not self.uv and v2 == self.vmax2:
                # Light on once continuous rotation reaches speed
                self.uv = True
                self.events.append((t, True))

        if not self.active():
            # Move complete: next move starts from rest at index speed
            self.v2 = START_V2
            self.vmax2 = INDEX_V2
            self.frac = 0.0
        return out if out else None


PRESS = const(1)
RELEASE = const(2)
LONG = const(3)


class Button:
    def __init__(self, gpio):
        pull = Pin.PULL_UP if BUTTON_ACTIVE_LOW else Pin.PULL_DOWN
        self.pin = Pin(gpio, Pin.IN, pull)
        self.raw = self.read()
        self.stable = self.raw
        self.changed_t = ticks_ms()
        self.press_t = 0
        self.long_sent = False

    def read(self):
        return self.pin.value() == (0 if BUTTON_ACTIVE_LOW else 1)

    def poll(self):
        """Return PRESS, RELEASE, LONG, or None."""
        now = ticks_ms()
        raw = self.read()
        if raw != self.raw:
            self.raw = raw
            self.changed_t = now
            return None
        if raw != self.stable and ticks_diff(now, self.changed_t) >= DEBOUNCE_MS:
            self.stable = raw
            if raw:
                self.press_t = now
                self.long_sent = False
                return PRESS
            return RELEASE
        if (self.stable and not self.long_sent
                and ticks_diff(now, self.press_t) >= LONG_PRESS_MS):
            self.long_sent = True
            return LONG
        return None


def check_config():
    if STEPS_PER_REV % DIVISIONS:
        raise ValueError("STEPS_PER_REV not divisible by DIVISIONS")
    min_interval = TICKS_PER_SEC / sqrt(max(CONT_V2, INDEX_V2))
    if min_interval < 2 * STEP_PULSE_US:
        raise ValueError("Speed too high for STEP_PULSE_US")


class Turntable:
    def __init__(self):
        check_config()
        self.enable_pin = Pin(ENABLE_PIN, Pin.OUT, value=ENABLE_AT_BOOT)
        self.rmt = make_rmt()
        self.button = Button(BUTTON_PIN)
        self.uv_pin = Pin(UV_PIN, Pin.OUT, value=0)
        self.motion = Motion()
        self.pending = None
        self.pending_events = []
        # (ticks_us deadline, level) UV changes for the chunk now playing
        self.scheduled = []
        # True when the current press has already been used (to stop
        # continuous rotation or to start it), so its release is not a
        # short press.
        self.consumed = False

    def poll(self):
        """One pass of button handling and pulse queueing.  Returns True
        while there is motion still to generate or play."""
        motion = self.motion
        sched = self.scheduled
        if sched:
            now = ticks_us()
            while sched and ticks_diff(sched[0][0], now) <= 0:
                self.uv_pin.value(sched.pop(0)[1])

        ev = self.button.poll()
        if ev == PRESS:
            self.consumed = False
            if motion.continuous():
                self.stop_continuous()
                self.consumed = True
        elif ev == LONG:
            if not self.consumed:
                motion.start_continuous()
                self.consumed = True
        elif ev == RELEASE:
            if not self.consumed:
                motion.add_index()

        # Keep one chunk computed ahead of the one the RMT is playing
        if self.pending is None and motion.active():
            self.pending = motion.build_chunk()
            self.pending_events = motion.events
            motion.events = []
        if self.pending is not None:
            if self.rmt.wait_done():
                self.rmt.write_pulses(self.pending, True)
                self.pending = None
                if self.pending_events:
                    # Time the UV changes to when the RMT reaches them
                    start = ticks_us()
                    for offset, level in self.pending_events:
                        sched.append((ticks_add(start, offset), level))
                    self.pending_events = []
            return True
        return bool(sched) or motion.active() or not self.rmt.wait_done()

    def uv_off(self):
        """Turn the UV light off now and cancel any pending turn-on."""
        self.uv_pin.value(0)
        self.motion.uv = False
        self.motion.events = []
        self.pending_events = []
        self.scheduled = []

    def stop_continuous(self):
        self.uv_off()
        self.motion.stop_continuous()

    def loop(self):
        """Run the pushbutton controller forever."""
        while True:
            if not self.poll():
                sleep_ms(5)

    def _poll_until(self, done=None):
        """Poll until motion finishes or done() returns True."""
        try:
            while self.poll():
                if done is not None and done():
                    return
        except KeyboardInterrupt:
            # Abandon the move.  The chunk already in the RMT plays out,
            # so the table stops abruptly, generally off an index position.
            m = self.motion
            if self.pending is not None:
                m.pos -= len(self.pending) // 2
                self.pending = None
            m.target = m.pos
            m.v2 = START_V2
            m.vmax2 = INDEX_V2
            m.frac = 0.0
            self.uv_off()
            print("Interrupted at step", m.pos)
            raise

    def wait(self):
        """Poll until all motion has finished."""
        self._poll_until()

    def index(self, n=1):
        """Index n eighths of a turn and wait for the move to finish."""
        if n < 1:
            raise ValueError("n must be >= 1")
        if self.motion.continuous():
            self.stop_continuous()
        for _ in range(n):
            self.motion.add_index()
        self.wait()

    def run(self, seconds):
        """Rotate continuously for the given time, then stop on the next
        index position and wait for the stop to finish."""
        self.motion.start_continuous()
        t0 = ticks_ms()
        ms = int(seconds * 1000)
        self._poll_until(lambda: ticks_diff(ticks_ms(), t0) >= ms)
        if self.motion.continuous():
            self.stop_continuous()
        self.wait()


    def step(self, n=1, interval_ms=10):
        """Send n single microsteps at interval_ms apart and wait, then
        report the electrical position so phase drive can be checked."""
        if n < 1:
            raise ValueError("n must be >= 1")
        self.wait()
        gap = interval_ms * 1000 - STEP_PULSE_US
        if not 0 < gap <= MAX_TICKS:
            raise ValueError("interval_ms out of range")
        self.rmt.write_pulses([STEP_PULSE_US, gap] * n, True)
        while not self.rmt.wait_done():
            pass
        m = self.motion
        m.pos += n
        m.target = m.pos
        m.frac = 0.0
        # One electrical cycle is 4 full steps.  Drivers such as A4988,
        # DRV8825 and TMC2xxx reset to 45 degrees (both phases at 71%).
        cycle = 4 * MICROSTEPS
        e = m.pos % cycle
        angle = 45.0 + 360.0 * e / cycle
        r = angle * 3.14159265 / 180.0
        print("step %d, microstep %d/%d in cycle, %.1f deg: "
              "ideal A %+.0f%% B %+.0f%% (if driver reset at power-up)"
              % (m.pos, e, cycle, angle % 360, 100 * cos(r), 100 * sin(r)))


    def enable(self, on):
        """Energize (True) or release (False) the motor."""
        self.enable_pin.value(1 if on else 0)


turntable = None


def index(n=1):
    """REPL: index n eighths of a turn."""
    turntable.index(n)


def run(seconds):
    """REPL: rotate continuously for seconds, then stop on an index."""
    turntable.run(seconds)


def step(n=1, interval_ms=10):
    """REPL: send n microsteps, interval_ms apart, and report phase."""
    turntable.step(n, interval_ms)


def enable(on=True):
    """REPL: energize (True) or release (False) the motor."""
    turntable.enable(on)


def loop():
    """REPL: start the pushbutton controller (Ctrl-C to exit)."""
    turntable.loop()


